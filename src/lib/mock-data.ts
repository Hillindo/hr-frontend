function deterministicScore(seed: string): number {
  let hash = 0;

  for (let i = 0; i < seed.length; i++) {
    hash = (hash * 31 + seed.charCodeAt(i)) % 1000;
  }

  return hash / 1000;
}

// Generate attendance records for the past 7 days
function generateAttendanceRecords(): AttendanceRecord[] {
  const records: AttendanceRecord[] = [];
  const today = new Date();

  employees.forEach((emp) => {
    for (let i = 0; i < 7; i++) {
      const date = new Date(today);
      date.setDate(date.getDate() - i);
      const dayOfWeek = date.getDay();

      // Skip weekends
      if (dayOfWeek === 0 || dayOfWeek === 6) continue;

      const score = deterministicScore(`${emp.id}-${i}`);
      let status: AttendanceRecord['status'] = 'PRESENT';
      let checkIn = '08:05';
      let checkOut = '17:02';
      let lateMinutes = 0;

      if (i === 0 && score < 0.25) {
        status = 'LATE';
        checkIn = '08:35';
        lateMinutes = 30;
      } else if (i === 1 && score < 0.15) {
        status = 'ABSENT';
        checkIn = '';
        checkOut = '';
      } else if (i === 2 && emp.profileCompleteness < 80) {
        status = 'SICK';
        checkIn = '';
        checkOut = '';
      }

      records.push({
        id: `att-${emp.id}-${i}`,
        employeeId: emp.id,
        employeeName: emp.fullName,
        employeeCode: emp.employeeCode,
        departmentName: emp.departmentName,
        workDate: date.toISOString().split('T')[0],
        checkInAt: checkIn || undefined,
        checkOutAt: checkOut || undefined,
        status,
        lateMinutes,
        source: 'SELF_SERVICE',
        notes: status === 'LATE' ? 'Terlambat karena macet' : undefined,
      });
    }
  });

  return records;
}

